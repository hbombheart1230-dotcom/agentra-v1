from __future__ import annotations

from typing import Any, Dict, Iterable, List, Tuple


def _normalize_symbol_code(value: Any, *, facade: Any) -> str:
    text = str(value or "").strip().upper()
    if text.startswith("A") and len(text) == 7:
        text = text[1:]
    return text
